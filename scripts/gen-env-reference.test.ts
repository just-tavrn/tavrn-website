// The configuration reference generator on a fixture (scripts/fixtures/env/env.example).
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { commentToMarkdown, isHeader, parseEnvExample, renderEnvReference, tableDescriptions } from "./gen-env-reference.mjs";

const fixture = readFileSync(join(dirname(fileURLToPath(import.meta.url)), "fixtures/env/env.example"), "utf8");
const SECTIONS = [
  { first: "EXAMPLE_DOMAIN", title: "Required" },
  { first: "TAVRN_NAME", title: "Node" },
  { first: "TAVRN_VOICE_ENABLED", title: "Voice", intro: true },
];
const OPTIONS = {
  title: "Configuration reference",
  description: "Every variable.",
  slug: "docs/admins/configuration-reference",
  label: "Configuration reference",
  order: 31,
  editUrl: "https://github.com/org/node/edit/main/deploy/.env.example",
  sourceUrl: "https://github.com/org/node/blob/main/deploy/.env.example",
  source: "node/deploy/.env.example",
  license: "AGPL-3.0-only",
};

describe("parsing .env.example", () => {
  it("finds sections by their short header lines when none are configured", () => {
    const sections = parseEnvExample(fixture);
    expect(sections.map((s) => [s.title, s.vars.map((v) => v.name)])).toEqual([
      ["Required", ["EXAMPLE_DOMAIN", "POSTGRES_PASSWORD"]],
      ["Node", ["TAVRN_NAME", "TAVRN_REGISTRATION", "TAVRN_ROOM_CREATION", "TAVRN_RATE_A", "TAVRN_RATE_B", "TAVRN_VOICE_ENABLED", "TAVRN_RTC_EXTERNAL_IP", "TAVRN_LOG_LEVEL"]],
    ]);
  });

  it("starts configured sections at their first variable, with the comment above as introduction", () => {
    const sections = parseEnvExample(fixture, { sections: SECTIONS });
    expect(sections.map((s) => s.title)).toEqual(["Required", "Node", "Voice"]);
    const voice = sections[2]!;
    expect(voice.intro.map((l) => l.trim())).toEqual([
      "Voice (protocol/VOICE.md). The node starts a media server; TAVRN_NAME names it.",
      "TAVRN_VOICE_ENABLED=false",
    ]);
    expect(voice.vars.map((v) => v.name)).toEqual(["TAVRN_VOICE_ENABLED", "TAVRN_RTC_EXTERNAL_IP", "TAVRN_LOG_LEVEL"]);
  });

  it("reads values, commented-out lines, notes, lead-ins and repeated variables", () => {
    const vars = new Map(parseEnvExample(fixture, { sections: SECTIONS }).flatMap((s) => s.vars).map((v) => [v.name, v]));
    expect(vars.get("TAVRN_NAME")).toMatchObject({ values: [{ value: "My node", commented: false }], notes: ["shown in the directory"] });
    expect(vars.get("TAVRN_ROOM_CREATION")?.values).toEqual([{ value: "invite", commented: true }]);
    expect(vars.get("TAVRN_RATE_A")?.leadIn).toEqual([" Limits per remote domain and minute:"]);
    expect(vars.get("TAVRN_RATE_B")?.leadIn).toEqual([" Limits per remote domain and minute:"]);
    expect(vars.get("TAVRN_RTC_EXTERNAL_IP")?.values).toEqual([
      { value: "203.0.113.7", commented: true },
      { value: "home.example", commented: true },
    ]);
    expect(vars.get("TAVRN_RTC_EXTERNAL_IP")?.description.map((l) => l.trim())).toEqual([
      "Addresses announced to clients: an IP address",
      "or a hostname, resolved every minute",
    ]);
    // An indented example line inside a comment is no variable of its own.
    expect([...vars.keys()].filter((k) => k === "TAVRN_VOICE_ENABLED")).toHaveLength(1);
  });

  it("recognizes header lines", () => {
    expect(isHeader(" Node")).toBe(true);
    expect(isHeader(" Reports (protocol/MODERATION.md §1)")).toBe(true);
    expect(isHeader(" Operations (TLS is done by the reverse proxy)")).toBe(false);
    expect(isHeader(" Per remote domain and minute:")).toBe(false);
  });
});

describe("rendering the reference", () => {
  const page = renderEnvReference(parseEnvExample(fixture, { sections: SECTIONS }), {
    ...OPTIONS,
    configurationRoute: "/docs/admins/configuration/",
    overrides: { POSTGRES_PASSWORD: { value: "a-long-random-password" }, EXAMPLE_DOMAIN: { display: "your domain" } },
    fallbacks: new Map([["TAVRN_LOG_LEVEL", "A log filter such as `info,sqlx=warn`."]]),
  });

  it("writes frontmatter and one table per section", () => {
    expect(page.startsWith('---\n# Generated by scripts/gen-env-reference.mjs from node/deploy/.env.example.')).toBe(true);
    expect(page).toContain('title: "Configuration reference"\n');
    expect(page).toContain("slug: docs/admins/configuration-reference\n");
    expect(page).toContain("  order: 31\n");
    expect(page).toContain("all 10 variables");
    expect(page.match(/^## /gm)).toHaveLength(3);
    expect(page.match(/^\| Variable \| Value in `\.env\.example` \| Description \|$/gm)).toHaveLength(3);
    expect(page).toContain("[Configuration](/docs/admins/configuration/)");
  });

  it("gives every variable an anchor", () => {
    expect(page).toContain('| <a id="TAVRN_NAME" href="#TAVRN_NAME"><code>TAVRN_NAME</code></a> | `My node` | shown in the directory |');
    for (const name of ["EXAMPLE_DOMAIN", "POSTGRES_PASSWORD", "TAVRN_RATE_B", "TAVRN_LOG_LEVEL"]) expect(page).toContain(`id="${name}"`);
  });

  it("escapes table cells and turns URLs, addresses, placeholders and variables into code", () => {
    expect(page).toContain("| `invite` | open \\| invite \\| closed |");
    expect(page).toContain("see `<docs>` and `https://example.org/rooms`, or ask `alice@example.org`.");
    expect(page).toContain("[`TAVRN_NAME`](#TAVRN_NAME) names it.");
    expect(page).toContain("Example: `TAVRN_VOICE_ENABLED=false`");
  });

  it("shows commented-out values, repeated values, overrides, lead-ins and fallbacks", () => {
    expect(page).toContain("| `invite` (commented out) |");
    expect(page).toContain("| `203.0.113.7` (commented out) or `home.example` (commented out) |");
    expect(page).toContain("| `a-long-random-password` |");
    expect(page).toContain("| your domain |");
    expect(page).toContain("| `60` (commented out) | Limits per remote domain and minute. |");
    expect(page).toContain("| `info` | A log filter such as `info,sqlx=warn`. |");
    expect(page).toContain("| `true` | See the introduction of this section. |");
  });

  it("is deterministic", () => {
    const again = renderEnvReference(parseEnvExample(fixture, { sections: SECTIONS }), {
      ...OPTIONS,
      configurationRoute: "/docs/admins/configuration/",
      overrides: { POSTGRES_PASSWORD: { value: "a-long-random-password" }, EXAMPLE_DOMAIN: { display: "your domain" } },
      fallbacks: new Map([["TAVRN_LOG_LEVEL", "A log filter such as `info,sqlx=warn`."]]),
    });
    expect(again).toBe(page);
  });
});

describe("helpers", () => {
  it("links references through the refs callback without escaping the inserted Markdown", () => {
    const refs = (text: string, hold: (md: string) => string) => text.replace(/VOICE\.md/g, () => hold("[VOICE.md](/docs/voice/)"));
    expect(commentToMarkdown("see VOICE.md §2, *not* <this>", new Set(), refs)).toBe("see [VOICE.md](/docs/voice/) §2, \\*not\\* `<this>`");
  });

  it("reads the variable tables of the handbook", () => {
    const table = [
      "| Variable | Default | Meaning |",
      "|---|---|---|",
      "| `TAVRN_A` | `1` | The first \\| one. |",
      "| `TAVRN_B` | Only two cells. |",
      "| not a variable | x | y |",
    ].join("\n");
    expect([...tableDescriptions(table)]).toEqual([
      ["TAVRN_A", "The first \\| one."],
      ["TAVRN_B", "Only two cells."],
    ]);
  });
});
