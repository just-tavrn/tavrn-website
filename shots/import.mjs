/**
 * Brings a run of the screenshot pipeline (README.md) into the website: copies the PNGs of <out> into
 * src/assets/screenshots/, removes the images there that the run no longer has, and writes
 * src/assets/screenshots/manifest.ts from the run's manifest.json (scene key = file name without .png, alt text,
 * caption and intended use). Astro makes the WebP variants and widths at build time.
 *   node shots/import.mjs <out> [manifest.json]      (default: <out>/manifest.json)
 */
import { copyFileSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "src/assets/screenshots");
const out = resolve(process.argv[2] ?? "");
if (!process.argv[2]) {
  console.error("usage: node shots/import.mjs <out> [manifest.json]");
  process.exit(2);
}
/** @type {{ scene: string, file: string, viewport: string, alt: string, caption: string, use: string[] }[]} */
const entries = JSON.parse(readFileSync(resolve(process.argv[3] ?? join(out, "manifest.json")), "utf8"));

const files = new Set(entries.map((e) => basename(e.file)));
for (const f of readdirSync(target).filter((f) => /\.(png|webp|jpe?g)$/.test(f) && !files.has(f))) rmSync(join(target, f));
for (const f of files) copyFileSync(join(out, f), join(target, f));

const ident = (/** @type {string} */ file) => file.replace(/\.png$/, "").replace(/-(\w)/g, (_, c) => c.toUpperCase());
const lines = [
  "// SPDX-License-Identifier: Apache-2.0",
  "/**",
  " * Every screenshot of the site in one place: scene key -> image, alt text, caption and where it is meant to be used.",
  " * Generated by shots/import.mjs from the screenshot pipeline's manifest.json (shots/README.md); change the alt texts",
  " * and captions in shots/make.ts and import a new run instead of editing this file. Pages and components use the",
  ' * keys only. Keys ending in "-phone" are drawn in a phone frame, the others in a window frame',
  " * (src/components/Shot.astro). The images show a local demo node with fictitious accounts.",
  " */",
  'import type { ImageMetadata } from "astro";',
  ...[...files].sort().map((f) => `import ${ident(f)} from "./${f}";`),
  "",
  "export interface Screenshot {",
  "  image: ImageMetadata;",
  "  alt: string;",
  "  caption: string;",
  "  /** Where the pipeline means the image to be used. */",
  '  use: readonly ("landing" | "docs")[];',
  "}",
  "",
  "export const screenshots = {",
  ...entries.flatMap((e) => [
    `  ${JSON.stringify(basename(e.file).replace(/\.png$/, ""))}: {`,
    `    image: ${ident(basename(e.file))},`,
    `    alt: ${JSON.stringify(e.alt)},`,
    `    caption: ${JSON.stringify(e.caption)},`,
    `    use: ${JSON.stringify(e.use).replace(/,/g, ", ")},`,
    "  },",
  ]),
  "} as const satisfies Record<string, Screenshot>;",
  "",
  "export type SceneKey = keyof typeof screenshots;",
  "",
  "export function screenshot(key: SceneKey): Screenshot {",
  "  return screenshots[key];",
  "}",
  "",
  "/** Phone scenes are drawn in a phone outline, the others in a window frame. */",
  "export function isPhone(key: SceneKey): boolean {",
  '  return key.endsWith("-phone");',
  "}",
  "",
];
writeFileSync(join(target, "manifest.ts"), lines.join("\n"));
console.log(`shots/import: ${files.size} screenshots -> src/assets/screenshots/`);
